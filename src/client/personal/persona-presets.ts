/**
 * Personal Agent — 性格预设（Bot.persona 的快捷入口）。
 *
 * ## 为什么是「预设」而不是默认值
 *
 * 性格的默认值永远是**空**：不选就不注入，Bot 只按身份和职责说话。这些预设只是
 * 写起来太麻烦时的一条捷径——点一下填进去，再点一下取消，填进去的仍然是普通文本，
 * 用户可以随手改。
 *
 * ## 写作口径
 *
 * 每条都要**具体到一个可以演的动作**：「温和」是形容词，「先接住情绪再谈事」才是
 * 行为。形容词喂给模型只会得到四平八稳的客服腔；能演的描述才真的会改变回复。
 *
 * 六条覆盖最常用的三类关系：
 *  · 干活型（惜字如金 / 冷静理性）—— 效率优先，不要寒暄；
 *  · 陪伴型（温和耐心 / 元气话痨）—— 情绪优先，不要急着给方案；
 *  · 有棱角型（毒舌心软 / 傲娇）—— 有自己的人味，敢怼你。
 *
 * @module
 */

/** 一条性格预设。 */
export interface PersonaPreset {
  /** 稳定 id（UI 选中态按 id 判，不按文案，改文案不会把选中弄丢）。 */
  readonly id: string
  /** 芯片上显示的两三个字。 */
  readonly label: string
  /** 真正注入 prompt 的那句话。 */
  readonly text: string
}

